import { useEffect, useMemo, useRef, useState } from 'react'
import { Link, useNavigate } from 'react-router-dom'
import TouchIcon from './TouchIcon'
import BatchResultList from './BatchResultList'
import { useTableMealsWorkspace } from '../features/tableMeals/useTableMealsWorkspace'
import { deliveryWarning, money, number, useShortageOrder } from '../features/order/useShortageOrder'
import { accountHref } from '../features/workspace/useDailyWork'
import type { PreviewRow } from '../api/shortageProcurement'
import './NextStepSheet.css'

/**
 * m버전 홈의 '다음 할 일' 시트(2026-10-16 사용자 결정: m버전은 기본 흐름을 3번 안에).
 *   새 주: ① 홈 '다음 주 식단 만들고 발주'(자동 식단) → ② '저장하고 발주서 보기'(저장 + 바로 시킬 품목 발주서) → ③ '공급사 N곳에 발주'
 *   식단 있음: ① 홈 '발주서 보기' → ② '공급사 N곳에 발주'
 * 자동 식단·저장·부족량·서버 재검증·전송은 식단표·발주하기 화면과 같은 훅(useTableMealsWorkspace, useShortageOrder)을 그대로 쓴다.
 * 기본값으로 처리할 수 없는 경우(예정 식수 없음, 식단을 못 만듦, 바로 시킬 품목 없음 등)는 이유와 '자세히' 버튼을 보여 주고 멈춘다.
 */
export type NextStep = { kind: 'meal' } | { kind: 'order'; override: Record<string, string>; title?: string }

export default function NextStepSheet({ accountId, step, onClose }: { accountId: string; step: NextStep; onClose: () => void }) {
  const [current, setCurrent] = useState<NextStep>(step)
  return <div className="t-sheet-backdrop" role="presentation" onClick={onClose}>
    <section className="t-sheet ns-sheet" role="dialog" aria-modal="true" aria-labelledby="ns-title" onClick={e => e.stopPropagation()}>
      {current.kind === 'meal'
        ? <MealStage accountId={accountId} onClose={onClose} onSaved={tableId => setCurrent({ kind: 'order', override: { account_id: accountId, source: 'PLAN', table_id: tableId, autoselect: '1' }, title: '방금 저장한 식단의 발주서' })} />
        : <OrderStage key={JSON.stringify(current.override)} accountId={accountId} override={current.override} title={current.title} onClose={onClose} />}
    </section>
  </div>
}

function Steps({ at }: { at: 1 | 2 | 3 }) {
  return <ol className="ns-steps" aria-label="진행">
    {['식단', '발주서', '발주'].map((label, index) => <li key={label} className={index + 1 === at ? 'is-current' : index + 1 < at ? 'is-done' : ''}><b>{index + 1}</b>{label}</li>)}
  </ol>
}

function MealStage({ accountId, onClose, onSaved }: { accountId: string; onClose: () => void; onSaved: (tableId: string) => void }) {
  const navigate = useNavigate()
  // ref(파일 입력·복원 설정)는 쓰지 않는다(렌더 중 ref 접근 금지 규칙)
  const { fileInputRef: _file, restoredSettings: _restored, ...w } = useTableMealsWorkspace()
  void _file; void _restored
  const started = useRef(false)
  const [servingsInput, setServingsInput] = useState('')
  const servings = Number(w.plannedServings)
  const configReady = w.accountMealConfiguration !== null && w.configuredMealSlotRows.length > 0

  // 식사 구성·예정 식수가 준비되면 자동 식단을 한 번 만든다(첫 클릭이 곧 '식단 만들기')
  useEffect(() => {
    if (started.current || !w.selectedAccountId || !configReady || !(servings > 0) || w.isAccountMenuLoading) return
    started.current = true
    void w.handleAutoGenerate()
  }, [configReady, servings, w])

  const check = w.savedStockCheck
  const result = w.autoGeneratedResult
  const shortage = check?.result?.ingredients ?? []
  const mealDays = useMemo(() => (result?.days ?? []).map(day => ({
    key: day.id, label: day.label || day.date,
    menus: w.configuredMealSlotRows.flatMap(row => (day.meals[row.key] ?? []).map(item => item.matchedMenu?.menu_name || item.text)),
  })), [result, w.configuredMealSlotRows])
  const message = w.autoGenerateMessage || w.tableSaveMessage
  const busy = !message && (!result || !check || check.loading)

  const save = async () => {
    if (!check) return
    const tableId = await w.persistPlan(check.payload)
    if (tableId) onSaved(tableId)
  }

  return <>
    <header className="t-sheet__head">
      <Steps at={1} />
      <h2 id="ns-title">{w.selectedAutoWeek?.label ?? '다음 주'} 식단</h2>
      <p>{servings > 0 ? `식사당 ${servings}명 · 자동 식단` : '자동 식단을 만들 예정 식수를 넣어 주세요'}</p>
    </header>
    <div className="t-sheet__body">
      {!(servings > 0) && <form className="ns-servings" onSubmit={e => { e.preventDefault(); if (Number(servingsInput) > 0) w.setPlannedServings(servingsInput) }}>
        <label>식사당 예정 식수<input className="t-input" inputMode="numeric" value={servingsInput} onChange={e => setServingsInput(e.target.value.replace(/\D/g, ''))} placeholder="예: 50" /></label>
        <button type="submit" className="t-btn is-primary" disabled={!(Number(servingsInput) > 0)}>자동 식단 만들기</button>
        <small>한 번 넣으면 다음부터는 기억합니다.</small>
      </form>}
      {servings > 0 && busy && <p className="t-msg" role="status">{!configReady ? '식사 구성을 불러오고 있습니다…' : !result ? '자동 식단을 만들고 있습니다…' : '식단 필요량과 재고를 확인하고 있습니다…'}</p>}
      {message && <p className="t-msg is-warn" role="alert">{message}</p>}
      {result && mealDays.length > 0 && <ul className="ns-days">{mealDays.map(day => <li key={day.key}><strong>{day.label}</strong><span>{day.menus.join(' · ') || '메뉴 없음'}</span></li>)}</ul>}
      {check && !check.loading && !check.error && <p className={`ns-note${shortage.length ? ' is-warn' : ''}`}>
        <TouchIcon name="order" size={18} />{shortage.length ? `모자란 식재료 ${shortage.length}개 · 저장하면 바로 시킬 품목으로 발주서를 만듭니다` : '이 식단으로 추가 발주할 식재료가 없습니다'}
      </p>}
      {check?.error && <p className="t-msg is-error" role="alert">재고 확인 실패: {check.error}</p>}
    </div>
    <footer className="t-sheet__actions">
      <button type="button" className="t-btn is-large" onClick={() => navigate(accountHref('/operations/table-meals', accountId))}>식단 고치기</button>
      <button type="button" className="t-btn is-primary is-large ns-main" disabled={!check || check.loading || !!check.error || w.isTableSaving} onClick={() => void save()}>
        {w.isTableSaving ? '저장 중…' : shortage.length ? '저장하고 발주서 보기' : '식단 저장'}
      </button>
      <button type="button" className="t-btn is-ghost" onClick={onClose}>닫기</button>
    </footer>
  </>
}

function OrderStage({ accountId, override, title, onClose }: { accountId: string; override: Record<string, string>; title?: string; onClose: () => void }) {
  const o = useShortageOrder(undefined, override)
  const asked = useRef(false)
  // 바로 시킬 품목이 골라지면 서버 재검증(발주서 확인)까지 바로 — 사람이 누르는 건 마지막 '발주'뿐
  useEffect(() => {
    if (asked.current || o.loading || !o.result || o.preview || o.previewing || o.selectionCount === 0) return
    asked.current = true
    void o.makePreview()
  }, [o])

  const sheets = useMemo(() => {
    const groups = new Map<string, { name: string; site: string; items: PreviewRow[]; amount: number }>()
    for (const row of o.preview?.items ?? []) {
      const key = `${row.offer.supplier_code}:${row.offer.external_site_code}`
      const group = groups.get(key) ?? { name: row.offer.supplier_name, site: row.offer.external_site_name, items: [], amount: 0 }
      group.items.push(row); group.amount += row.item_amount; groups.set(key, group)
    }
    return [...groups.values()]
  }, [o.preview])
  const total = o.result?.ingredients.length ?? 0
  const excluded = o.preview ? total - o.preview.items.length : 0
  const detail = `/order_manager/order?${new URLSearchParams({ ...override, tab: override.source === 'STOCK' ? 'stock' : 'plan' })}`
  const nothing = o.result && !o.loading && o.selectionCount === 0 && !o.preview && !o.completed

  return <>
    <header className="t-sheet__head">
      <Steps at={o.completed ? 3 : 2} />
      <h2 id="ns-title">{o.completed ? '발주를 보냈어요' : title || '발주서'}</h2>
      <p>{o.preview ? `납품일 ${o.preview.criteria.delivery_date} · 발주서 ${sheets.length}장 · ${o.preview.items.length}품목` : `납품일 ${o.criteria.delivery_date}`}</p>
    </header>
    <div className="t-sheet__body">
      {(o.loading || o.previewing) && <p className="t-msg" role="status">{o.previewing ? '공급사 가격·발주 가능 여부를 다시 확인하고 있습니다…' : '모자란 식재료를 계산하고 있습니다…'}</p>}
      {o.error && <p className="t-msg is-error" role="alert">{o.error}</p>}
      {nothing && <p className="t-msg is-warn">{total ? `모자란 식재료 ${total}개 중 바로 시킬 수 있는 품목이 없습니다(납품·마감 조건 확인 필요 등). '자세히 고르기'에서 직접 골라 주세요.` : '지금 발주할 식재료가 없습니다.'}</p>}
      {sheets.map(sheet => <section key={sheet.name + sheet.site} className="ns-order">
        <header><strong>{sheet.name}</strong><span>{sheet.site}</span><b>{money(sheet.amount)}원</b></header>
        <ul>{sheet.items.map(row => <li key={row.ingredient_id}>
          <span><strong>{row.ingredient_name}</strong><small>{row.offer.product_name}</small>
            {deliveryWarning(row.offer, o.preview!.criteria.delivery_date, o.guidanceNow) && <small className="ns-issue">{deliveryWarning(row.offer, o.preview!.criteria.delivery_date, o.guidanceNow)}</small>}</span>
          <span>{number(row.order_qty)} {row.offer.order_unit}</span>
          <strong>{money(row.item_amount)}원</strong>
        </li>)}</ul>
      </section>)}
      {o.preview && <div className="t-summary"><div className="is-total"><span>상품금액 합계</span><span>{money(o.preview.item_amount)}원</span></div></div>}
      {excluded > 0 && !o.completed && <p className="ns-note is-warn"><TouchIcon name="alert" size={18} />자동으로 넣지 않은 품목 {excluded}개(조건 확인 필요·상품 미연결 등) · <Link to={detail}>자세히 고르기</Link></p>}
      {o.message && <p className="t-msg is-warn" role="status">{o.message}</p>}
      {o.batchResult && <BatchResultList result={o.batchResult} accountId={accountId} />}
    </div>
    <footer className="t-sheet__actions">
      {o.completed
        ? <><button type="button" className="t-btn is-large" onClick={onClose}>닫기</button>
          <Link className="t-btn is-primary is-large ns-main" to={accountHref('/order_manager/orders', accountId)}>발주서·입고 보기</Link></>
        : <><Link className="t-btn is-large" to={detail}>자세히 고르기</Link>
          <button type="button" className="t-btn is-primary is-large ns-main" disabled={!o.preview || o.submitting || o.previewing} onClick={() => void o.submit()}>
            {o.submitting ? '발주 중…' : `공급사 ${sheets.length || ''}곳에 발주`}
          </button>
          <button type="button" className="t-btn is-ghost" disabled={o.submitting} onClick={onClose}>닫기</button></>}
    </footer>
  </>
}
